/// In-app AR/EN string tables. Arabic is the default language and drives RTL.
/// Keys must stay in sync between both maps (covered by a unit test).
class L10n {
  L10n._();

  static String lang = 'ar';

  static bool get isArabic => lang == 'ar';

  static String t(String key) {
    final map = lang == 'en' ? en : ar;
    return map[key] ?? en[key] ?? key;
  }

  static String f(String key, Map<String, String> params) {
    var value = t(key);
    params.forEach((k, v) {
      value = value.replaceAll('{$k}', v);
    });
    return value;
  }
}

